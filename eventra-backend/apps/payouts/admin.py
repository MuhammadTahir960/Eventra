class IssuedNumberForm(forms.Form):
    account_number_display = forms.CharField(
        label="Account number",
        disabled=True,
        required=False,
        help_text="Generated by Eventra. It can't be typed or changed.",
    )
    number_token = forms.CharField(widget=forms.HiddenInput)

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        if self.is_bound:
            try:
                number = account_numbers.redeem(self.data.get("number_token", ""))
            except signing.BadSignature:
                number = ""
        else:
            issued = account_numbers.issue()
            self.initial["number_token"] = issued["token"]
            number = issued["number"]
        self.fields["account_number_display"].initial = number

    def clean_number_token(self):
        token = self.cleaned_data["number_token"]
        try:
            ensure_account_number_free(token)
        except (InvalidAccountNumberError, AccountNumberTakenError) as exc:
            raise forms.ValidationError(f"{exc} Reload the page.") from exc
        return token


class NewPartnerForm(IssuedNumberForm, forms.ModelForm):
    method = forms.ChoiceField(label="Paid to", choices=PayoutAccount.Method.choices)
    provider = PayoutAccount._meta.get_field("provider").formfield()
    holder_name = PayoutAccount._meta.get_field("holder_name").formfield()

    class Meta:
        model = Partner
        fields = ["name", "is_active"]


@admin.register(Partner)
class PartnerAdmin(admin.ModelAdmin):
    list_display = ("name", "is_active", "created_at")
    list_filter = ("is_active",)
    search_fields = ("name",)
    readonly_fields = ("payout_details",)

    def get_fields(self, request, obj=None):
        if obj:
            return ("name", "is_active", "payout_details")
        return (
            "name",
            "is_active",
            "method",
            "provider",
            "holder_name",
            "account_number_display",
            "number_token",
        )

    def get_readonly_fields(self, request, obj=None):
        return self.readonly_fields if obj else ()

    def get_form(self, request, obj=None, **kwargs):
        if obj is None:
            kwargs["form"] = NewPartnerForm
        return super().get_form(request, obj, **kwargs)

    def save_model(self, request, obj, form, change):
        if change:
            return super().save_model(request, obj, form, change)
        with transaction.atomic():
            super().save_model(request, obj, form, change)
            create_payout_account(
                partner=obj,
                **{
                    field: form.cleaned_data[field]
                    for field in ("number_token", "method", "provider", "holder_name")
                },
            )

    @admin.display(description="Payout details")
    def payout_details(self, obj):
        account = getattr(obj, "payout_account", None)
        if account is None:
            return "None"
        return (
            f"{account.get_method_display()}, {account.provider}, "
            f"{account.holder_name}, {account_numbers.masked(account.account_number)}"
            " (edit the provider and holder under Payout accounts)"
        )

    def has_delete_permission(self, request, obj=None):
        return False


class NewPayoutAccountForm(IssuedNumberForm, forms.ModelForm):
    class Meta:
        model = PayoutAccount
        fields = ["organizer", "method", "provider", "holder_name"]

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.fields["organizer"].required = True
        self.fields["organizer"].queryset = User.objects.filter(
            role=Roles.ORGANIZER, payout_account__isnull=True
        )


@admin.register(PayoutAccount)
class PayoutAccountAdmin(admin.ModelAdmin):
    list_display = ("holder_name", "organizer", "partner", "method", "masked_number")
    list_select_related = ("organizer", "partner")
    list_filter = ("method",)
    search_fields = ("holder_name", "provider", "partner__name", "organizer__email")
    readonly_fields = ("organizer", "partner", "method", "masked_number")

    def get_readonly_fields(self, request, obj=None):
        return self.readonly_fields if obj else ()

    def get_fields(self, request, obj=None):
        if obj:
            return (*self.readonly_fields, "provider", "holder_name")
        return (
            "organizer",
            "method",
            "provider",
            "holder_name",
            "account_number_display",
            "number_token",
        )

    def get_form(self, request, obj=None, **kwargs):
        if obj is None:
            kwargs["form"] = NewPayoutAccountForm
        return super().get_form(request, obj, **kwargs)

    def save_model(self, request, obj, form, change):
        if not change:
            obj.account_number = encrypted_number(form.cleaned_data["number_token"])
        super().save_model(request, obj, form, change)

    def has_delete_permission(self, request, obj=None):
        return False  # accounts are locked

    @admin.display(description="Account number")
    def masked_number(self, obj):
        return account_numbers.masked(obj.account_number)
